function firstOr(list: string[], index: number, fallback: string): string {
  const raw = list[index]?.trim();
  return raw && raw.length > 0 ? raw : fallback;
}

function trimEnd(text: string): string {
  return text.replace(/[\s.،؛:]+$/, "");
}

/** Turn a point sentence into a specific, readable heading. */
function headline(text: string): string {
  const clean = text.replace(/\s+/g, " ").trim();
  const clauses = clean.split(/[،؛:]|\.\s|\.$/).map((part) => part.trim()).filter(Boolean);
  let head = clauses[0] ?? clean;
  if (head.split(" ").length < 3 && clauses[1]) head = `${head}، ${clauses[1]}`;
  const words = head.split(" ");
  if (words.length > 9) head = words.slice(0, 9).join(" ");
  return trimEnd(head) || trimEnd(clean);
}

function topicOf(spec: ArticleSpec): string {
  return trimEnd(spec.title.split(":")[0].split("؟")[0]) || spec.h1;
}

