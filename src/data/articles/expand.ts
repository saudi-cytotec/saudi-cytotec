import { emergency, h2, h3, info, p, ul, warn } from "../../utils/content";
import type { Article, ArticleFaq, ClusterId, ContentBlock } from "../../types";
import { edu } from "./build";

export interface ArticleSpec {
  slug: string;
  title: string;
  h1: string;
  metaTitle: string;
  metaDescription: string;
  excerpt: string;
  related: string[];
  points: string[];
  faqs: ArticleFaq[];
}

const closings: Record<ClusterId, string> = {
  definition: "بعد فهم التسمية والمادة، انتقلي إلى صفحات الأمان والمصادر قبل أي استنتاج عملي.",
  uses: "الاستخدام الطبي قرار مهني داخل نظام صحي، وليس قائمة خيارات تُنتقى من المقالات.",
  safety: "التحذير جزء من هوية الدواء. تجاهله لا يجعل الحالة أبسط، بل يجعل القرار أعمى.",
  "side-effects": "العرض المزعج يختلف عن العلامة الطارئة. عند الشك اختاري الجهة الصحية لا انتظار المنشورات.",
  pregnancy: "الحمل المبكر يحتاج متابعة سريرية. المقال يجهّز الأسئلة ولا يؤكد سلامة أي دواء.",
  "womens-health": "صحة المرأة أوسع من اسم دواء واحد، والفحص الدوري أقصر طريق لتفسير الأعراض.",
  faq: "السؤال الجيد يبدأ من المصدر والسياق، لا من الجملة الأكثر تداولاً.",
  interactions: "الموانع والتداخلات لا تُستنتج من الذاكرة. تاريخك الدوائي يستحق أن يُذكر كاملاً للطبيب.",
  emergency: "الوقت في العلامات الحادة قيمة طبية. لا تؤجلي الرعاية لأن المقال لم يذكر حرفياً عرضك.",
  evidence: "قوة الدليل تُقاس بالمنهج وقابلية التحقق، لا بثقة الكاتب أو انتشار المنشور.",
};

export function expand(cluster: ClusterId, spec: ArticleSpec): Article {
  const blocks: ContentBlock[] = [
    p(`${spec.excerpt} هذا النص يرتّب الفكرة داخل إطار تعليمي عام، ويبقي القرار الفردي حيث يجب أن يبقى: عند طبيب أو صيدلاني مرخّص.`),
    p("الخلط المتكرر على الإنترنت يأتي من دمج ثلاثة أمور مختلفة: الاسم التجاري، والمادة الفعالة، والسياق السريري. المقال يفصل بينها حتى لا تُنقل معلومة من مستشفى إلى قرار منزلي."),
    h2("السياق الذي يُفهم فيه هذا الموضوع"),
    p(spec.points[0] ?? "الموضوع لا يُختزل في جملة واحدة لأن النشرات التنظيمية تضع الاستطباب والتحذير في الصفحة نفسها."),
    p("في المملكة العربية السعودية يخضع تداول الأدوية لرقابة الهيئة العامة للغذاء والدواء، وتُقدَّم الخدمات عبر المنشآت المرخصة. هذا الإطار أهم من أي تسمية شائعة."),
    h2("ما الذي توضحه المراجع العامة؟"),
    p(spec.points[1] ?? "النشرات الرسمية تصف المركب والاستطباب المعتمد والآثار الضارة، لكنها لا تعرف حالتك ولا تاريخك الجراحي ولا احتمال الحمل."),
    ul(spec.points.slice(2, 6).length ? spec.points.slice(2, 6) : [
      "المعلومة العامة تساعد على طرح سؤال أفضل في العيادة.",
      "المعلومة العامة لا تستبدل الفحص أو التحاليل.",
      "جودة المصدر جزء من الأمان لا تفصيل تجميلي.",
      "غياب العرض بعد تصرف غير منضبط لا يثبت الأمان.",
    ]),
    h2("حدود التعليم وما لا يقدمه هذا المقال"),
    p("لن تجدي هنا جرعة أو خطة تنفيذ أو مساراً للشراء. هذه الحدود مقصودة لأنها تحمي القارئ من التعامل مع نص عام وكأنه موافقة مستنيرة."),
    warn("أي محتوى يطلب تواصلاً خاصاً لبيع الدواء أو يدّعي ضماناً فردياً دون فحص ليس مصدراً طبياً."),
    h3("علامات تستدعي الخروج من القراءة إلى الرعاية"),
    p("النزيف الغزير، الإغماء، الألم البطني الحاد، الحمى المرتفعة، وضيق التنفس ليست موضوعات للنقاش المؤجل."),
    emergency("إذا كان لديك حمل مؤكد أو محتمل مع ألم أحادي الجانب أو دوخة شديدة، اعتبري الوضع طارئاً حتى يثبت العكس سريرياً."),
    h2("كيف تستخدمين هذه الصفحة عملياً؟"),
    p(spec.points[6] ?? "اكتبي أسئلتك قبل المراجعة: المادة لا الاسم فقط، الأعراض وتوقيتها، والأدوية الأخرى، وأي احتمال للحمل."),
    info(closings[cluster]),
    p("إخلاء المسؤولية: المحتوى تعليمي عام ولا يُعد استشارة طبية أو خطة علاج فردية، ولا يغني عن مراجعة جهة صحية مرخصة."),
  ];

  return edu(cluster, {
    slug: spec.slug,
    title: spec.title,
    h1: spec.h1,
    metaTitle: spec.metaTitle,
    metaDescription: spec.metaDescription,
    excerpt: spec.excerpt,
    imageAlt: "عنصر بصري هادئ لمحتوى طبي تعليمي",
    related: spec.related,
    blocks,
    faqs: spec.faqs,
  });
}
