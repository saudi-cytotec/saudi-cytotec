/**
 * Article builder — content-recovery template.
 *
 * Policy (see docs/article-content-recovery-report.md):
 *  - Every body paragraph is anchored to a sentence that is unique to its own
 *    article (its `points`), so no two articles publish an identical paragraph.
 *  - Headings are derived from the article's own points, so H2/H3 describe the
 *    specific subject instead of a generic template.
 *  - Medical-safety text (pregnancy warning, emergency signs, prescription-only
 *    framing, non-systematic-source warning) is KEPT for every article, but the
 *    wording rotates inside a small bounded set — repeating a warning verbatim
 *    in 100 articles is what made the catalog look templated.
 *  - No dosing, no procedures, no home protocols, no purchasing routes and no
 *    self-treatment instructions are generated here, ever.
 *  - FAQs are not repeated inside the body: they are rendered once by
 *    ArticlePage from `article.faqs` (schema + visible list).
 */

