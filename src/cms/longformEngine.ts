export function composeLongform(input: GenerationRequest): ContentBlock[] {
  return [...coreSections(input), ...expansionPacks(input).flat(), disclaimer()];
}

export function expandLongform(
  current: ContentBlock[],
  input: GenerationRequest,
  _missing: number,
  expansionIndex: number,
): ContentBlock[] {
  const packs = expansionPacks(input);
  const pack = packs[expansionIndex];
  if (!pack) return current;
  const main = current.filter((block) => !isDisclaimerBlock(block));
  const notes = current.filter(isDisclaimerBlock);
  return [...main, ...pack, ...(notes.length ? notes : [disclaimer()])];
}
