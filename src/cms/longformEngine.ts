export interface GenerationRequest {
  topic: string;
  primaryKeyword: string;
  cluster: string;
  searchIntent?: string;
  articleType?: string;
}

function p(text: string): ContentBlock {
  return { type: "p", text };
}
function h2(text: string): ContentBlock {
  return { type: "h2", text };
}
function h3(text: string): ContentBlock {
  return { type: "h3", text };
}
function ul(items: string[]): ContentBlock {
  return { type: "ul", items };
}
function warn(text: string): ContentBlock {
  return { type: "callout", text, tone: "warning" };
}
function emergency(text: string): ContentBlock {
  return { type: "callout", text, tone: "emergency" };
}
function info(text: string): ContentBlock {
  return { type: "callout", text, tone: "info" };
}

